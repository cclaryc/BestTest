"""Regenerate the pinned dependency lists.

    python scripts/lock.py

Writes two files next to pyproject.toml:

* ``requirements.lock``      exact versions of everything the service runs on;
                             the container image installs exactly these.
* ``requirements-dev.lock``  the same plus the test and lint tools; CI installs
                             with ``-c requirements-dev.lock`` so that a new
                             release of a tool cannot break the build overnight.

``pyproject.toml`` says which versions are acceptable. These files record which
versions were actually tested together. Run this on Linux with the Python
version the container uses, then run the tests before committing the result.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import venv
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
PACKAGE = "besttest-analysis"


def freeze(extra: str) -> list[str]:
    with tempfile.TemporaryDirectory() as directory:
        venv.create(directory, with_pip=True)
        scripts = "Scripts" if sys.platform == "win32" else "bin"
        python = str(Path(directory) / scripts / "python")
        subprocess.run(
            [python, "-m", "pip", "install", "--quiet", f"{PROJECT}{extra}"],
            check=True,
        )
        frozen = subprocess.run(
            [python, "-m", "pip", "freeze", "--exclude", PACKAGE],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    return sorted(line for line in frozen.splitlines() if line and "==" in line)


def write(name: str, purpose: str, pins: list[str]) -> None:
    header = [
        f"# {purpose}",
        f"# Generated by scripts/lock.py with Python {sys.version_info.major}"
        f".{sys.version_info.minor}. Do not edit by hand.",
    ]
    (PROJECT / name).write_text("\n".join([*header, *pins]) + "\n", encoding="utf-8", newline="\n")
    print(f"{name}: {len(pins)} packages")


def main() -> int:
    write("requirements.lock", "Exact versions the service runs on.", freeze(""))
    write("requirements-dev.lock", "Runtime versions plus test and lint tools.", freeze("[dev]"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
